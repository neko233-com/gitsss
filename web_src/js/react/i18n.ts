export function tr(key: keyof typeof english, values: Record<string, string | number> = {}, lang = document.documentElement.lang): string {
  const text = lang.toLowerCase().startsWith('zh') ? key : english[key];
  return text.replace(/\{(\w+)\}/g, (placeholder, name: string) => Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}
